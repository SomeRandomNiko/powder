class Client:
    def __init__(self, reader, writer):
        self.reader, self.writer = reader, writer

    async def send(self, fields):
        self.writer.write(pb.frame(pb.encode(fields)))
        await self.writer.drain()

    async def recv(self) -> list:
        n = int.from_bytes(await asyncio.wait_for(self.reader.readexactly(4), 3), "big")
        return pb.decode(await self.reader.readexactly(n))

    async def request(self, rid, kind, body) -> list:
        await self.send([(1, [(1, rid), (kind, body)])])
        rsp = pb.decode(pb.first(await self.recv(), 1))
        assert pb.first(rsp, 1) == rid
        return pb.decode(pb.first(rsp, kind))

    async def data(self, cid, msg: bytes) -> bytes:
        await self.send([(2, [(1, [(1, cid), (2, pb.frame(msg))])])])
        d = pb.decode(pb.first(pb.decode(pb.first(await self.recv(), 2)), 1))
        assert pb.first(d, 1) == cid
        return pb.unframe(pb.first(d, 2))


async def test_session_over_tls(demux):
    services, pki, port = demux
    ctx = ssl.create_default_context(cafile=str(pki.ca_pem))   # verifies the name like Connect does
    reader, writer = await asyncio.open_connection("127.0.0.1", port, ssl=ctx,
                                                   server_hostname="dmx.upc.ubisoft.com")
    c = Client(reader, writer)
    try:
        await c.send([(2, [(4, [(1, 13380)])])])                       # client newer than the recording
        patch = await c.request(1, 5, [(1, 0)])
        assert pb.first(patch, 5) == 13380 and pb.first(patch, 1) == 1   # "up to date", rest as recorded
        utility = await c.request(0, 6, [(1, "utility_service"), (2, b"")])
        geo = pb.decode(pb.first(pb.decode(pb.first(pb.decode(pb.first(utility, 2)), 1)), 1))
        assert pb.text(geo, 1) == services.config.server.country      # from config, not a recording

        auth = await c.request(2, 2, [(1, [(3, "any-ticket")]), (2, "uplay_pc")])
        assert pb.first(auth, 1) == 1                                   # lenient: unknown ticket ok

        own = await c.request(3, 3, [(2, "ownership_service")])
        ach = await c.request(4, 3, [(2, "ach_frontend")])
        cid_own, cid_ach = pb.first(own, 1), pb.first(ach, 1)
        assert pb.first(own, 2) == 1 and cid_own != cid_ach

        # owned games: Steep's products from the pack, not the rest of the library, cloud saves off
        reply = pb.decode(pb.first(pb.decode(await c.data(cid_own, pb.encode([(1, [(1, 8), (2, b"")])]))), 1))
        assert pb.first(reply, 1) == 8
        products = [pb.decode(v) for n, v, _ in pb.decode(pb.first(pb.decode(pb.first(reply, 2)), 2))]
        assert sorted(pb.first(p, 1) for p in products) == [synthetic.STEEP_STEAM, synthetic.STEEP, synthetic.ADDON]
        assert all(b"cloud_saves: yes" not in pb.first(p, 17, b"") for p in products)

        # ownership token request (nested style): a fresh token, our request id
        reply = pb.decode(pb.first(pb.decode(await c.data(cid_own, pb.encode(
            [(1, [(1, 9), (14, [(1, 3280)])])]))), 1))
        assert pb.first(reply, 1) == 9
        token = pb.decode(pb.first(reply, 13))
        assert pb.first(token, 1) == 1 and len(pb.text(token, 2)) > 100

        # flat style
        reply = pb.decode(await c.data(cid_ach, pb.encode([(1, 6), (4, b"")])))
        assert pb.first(reply, 1) == 6

        await c.send([(2, [(6, [(1, 3280)])])])                        # product started: no reply
        await c.send([(2, [(3, b"")])])                                 # keep-alive: no reply
        own2 = await c.request(5, 3, [(2, "friends_service")])          # connection still healthy
        assert pb.first(own2, 2) == 1
    finally:
        writer.close()


async def test_patch_check_on_its_own_connection_gets_the_reported_version(demux):
    """Connect asks for patch info on short connections of its own, without reporting its version there
    (as in the real traffic); it must still hear its own version, not the recorded one."""
    services, pki, port = demux
    ctx = ssl.create_default_context(cafile=str(pki.ca_pem))

    async def connect():
        reader, writer = await asyncio.open_connection("127.0.0.1", port, ssl=ctx,
                                                       server_hostname="dmx.upc.ubisoft.com")
        return Client(reader, writer), writer

    main, w1 = await connect()
    check, w2 = await connect()
    try:
        await main.send([(2, [(4, [(1, 13380)])])])                     # main connection: version push
        await main.request(1, 2, [(1, [(3, "any-ticket")]), (2, "uplay_pc")])   # round trip: push handled
        patch = await check.request(0, 5, [(1, "174.0"), (2, 0)])      # patch query, no version
        assert pb.first(patch, 5) == 13380
        assert services.repos.kv.get("server", "connect_version") == 13380      # kept across restarts
    finally:
        w1.close()
        w2.close()


